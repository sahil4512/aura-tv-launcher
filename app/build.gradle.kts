import java.util.Properties

plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
}

android {
    namespace = "com.auratv.launcher"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.auratv.launcher"
        // API 22 (Android 5.1) keeps the door open for older Android TV boxes;
        // the primary target (Fire TV Stick 4K, Fire OS 6) is API 25.
        minSdk = 22
        targetSdk = 34
        versionCode = 18
        versionName = "0.6.7"
        // Fire TV Stick 4K is armeabi-v7a, but there is no native code, so the APK is ABI-neutral.
    }

    signingConfigs {
        // Release builds are signed with a local key generated by tools/make-keystore.sh
        // (falls back to the debug key if the keystore is absent so the build never breaks).
        // Passwords live in keystore/signing.properties, which (like the key) is never committed.
        create("release") {
            val ks = rootProject.file("keystore/aura-release.jks")
            val creds = rootProject.file("keystore/signing.properties")
            if (ks.exists() && creds.exists()) {
                val p = Properties().apply { creds.inputStream().use { load(it) } }
                storeFile = ks
                storePassword = p.getProperty("storePassword")
                keyAlias = p.getProperty("keyAlias", "aura")
                keyPassword = p.getProperty("keyPassword")
            } else {
                val debug = signingConfigs.getByName("debug")
                storeFile = debug.storeFile
                storePassword = debug.storePassword
                keyAlias = debug.keyAlias
                keyPassword = debug.keyPassword
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.getByName("release")
        }
        debug {
            applicationIdSuffix = ""
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }
    buildFeatures {
        buildConfig = true
    }
    androidResources {
        // Wallpapers are already-compressed JPEGs.
        noCompress += listOf("jpg")
    }
    testOptions {
        unitTests.isReturnDefaultValues = true
    }
    lint {
        abortOnError = false
    }
}

dependencies {
    // Intentionally no AndroidX / Leanback / Play Services: the launcher is built on framework
    // Views only to keep cold start, APK size and RAM as low as possible.
    testImplementation("junit:junit:4.13.2")
    testImplementation("org.json:json:20240303") // real JSON parsing for the photo-feed tests (Android's is a stub on the JVM)
}
